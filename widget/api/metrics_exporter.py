logger = logging.getLogger(__name__)

def get_or_create_gauge(name: str, documentation: str, labelnames: list[str]) -> Gauge:
    """Helper to return an existing Gauge from the registry or create a new one."""
    # Find existing collector in the registry
    collector = REGISTRY._names_to_collectors.get(name)
    if collector and isinstance(collector, Gauge):
        return collector
    return Gauge(name, documentation, labelnames)

